"""
Обработчик блока «Мотивация»: случайная цитата.
"""

import random
import logging
from aiogram import Router, F
from aiogram.types import Message

from keyboards import main_menu_kb

logger = logging.getLogger(__name__)
router = Router()

# 20 мотивационных цитат на русском
QUOTES: list[str] = [
    "Образование — это самое мощное оружие, которым можно изменить мир. — Нельсон Мандела",
    "Тяжело в учении — легко в бою. — Александр Суворов",
    "Начинай делать то, что нужно. Потом делай то, что возможно. И вдруг ты уже делаешь невозможное. — Франциск Ассизский",
    "Секрет вперёд — начать. — Марк Твен",
    "Успех — это способность идти от неудачи к неудаче, не теряя энтузиазма. — Уинстон Черчилль",
    "Учись так, будто тебе предстоит жить вечно; живи так, будто тебе предстоит умереть завтра. — Махатма Ганди",
    "Наука — это организованные знания, мудрость — это организованная жизнь. — Иммануил Кант",
    "Дорогу осилит идущий.",
    "Не ошибается тот, кто ничего не делает. — Теодор Рузвельт",
    "Знания — единственное, что нельзя отнять у человека.",
    "Каждый мастер когда-то был любителем.",
    "Ты не можешь изменить ветер, но можешь настроить паруса.",
    "Будущее принадлежит тем, кто верит в красоту своей мечты. — Элеонора Рузвельт",
    "Стремись не к тому, чтобы добиться успеха, а к тому, чтобы твоя жизнь имела смысл. — Альберт Эйнштейн",
    "Маленькие шаги каждый день приводят к большим результатам.",
    "Инвестиции в знания приносят наибольший доход. — Бенджамин Франклин",
    "Сложно — не значит невозможно. Это значит, что тебе придётся постараться.",
    "Самый тёмный час — перед рассветом.",
    "Единственный способ сделать великую работу — любить то, что делаешь. — Стив Джобс",
    "Препятствия — это те страшные вещи, которые видишь, когда отводишь взгляд от цели. — Генри Форд",
]


@router.message(F.text == "💪 Мотивация")
async def on_motivation(message: Message) -> None:
    """Случайная мотивационная цитата."""
    quote = random.choice(QUOTES)
    await message.answer(
        f"💪 *Мотивация дня:*\n\n_{quote}_",
        parse_mode="Markdown",
        reply_markup=main_menu_kb(),
    )
